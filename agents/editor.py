from __future__ import annotations
from typing import List, Dict
from datetime import datetime
from agents.base_agent import BaseAgent


class Editor(BaseAgent):
    name = "Agent D — Editor"
    persona = (
        "You are the Editor in a multi-agent research system. Compile verified findings "
        "from multiple sub-tasks into a single, well-structured Markdown report. "
        "Use headings per sub-task, cite sources inline as [n], and add a 'Sources' "
        "section at the end. Clearly flag any CONTRADICTED or UNVERIFIED claims rather "
        "than presenting them as fact. Be concise, professional, and avoid repetition."
    )

    def compile_report(self, query: str, verified_results: List[Dict]) -> str:
        sections = []
        all_sources = []
        for r in verified_results:
            claims_txt = "\n".join(
                f"- {v.get('claim')} ({v.get('verdict')}) — {v.get('note', '')}"
                for v in r.get("verified_claims", [])
            )
            src_txt = ", ".join(s["title"] or s["url"] for s in r.get("sources", []))
            all_sources.extend(r.get("sources", []))
            sections.append(f"### {r['sub_task']}\nSources consulted: {src_txt}\n\n{claims_txt}")

        raw = self.think(
            f"Original research query: {query}\n\n"
            f"Findings by sub-task:\n\n" + "\n\n".join(sections) +
            "\n\nCompile the final Markdown report now.",
            max_tokens=2500,
        )

        footer = f"\n\n---\n*Generated by SentinelSearch on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}*"
        return raw.strip() + footer
